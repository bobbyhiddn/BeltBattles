#!/usr/bin/env node
// ARTB-CODE-1 (REQ-BFG-126, REQ-BFG-127), item D: the art direction B data in the repo, and its generator.
//
//   node tools/artb/gen.mjs            read tools/artb/artb-slice.json and write src/render/artBData.ts
//   node tools/artb/gen.mjs --check    exit 1 when src/render/artBData.ts is not what the JSON generates (exit 0 when it is)
//
// tools/artb/artb-slice.json is a byte copy of the art lane's file (legend, legendHex, sprites, work). New art later = replace the JSON,
// run this, re-measure the pins: nothing in src/render/artBData.ts is ever edited by hand. Plain node, no dependency, no randomness:
// the same JSON always writes the same bytes (the header names the JSON's sha256).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const JSON_PATH = join(HERE, "artb-slice.json");
const OUT_PATH = join(HERE, "..", "..", "src", "render", "artBData.ts");

const raw = readFileSync(JSON_PATH);
const sha = createHash("sha256").update(raw).digest("hex");
const data = JSON.parse(raw.toString("utf8"));

const fail = (msg) => { console.error(`gen.mjs: ${msg}`); process.exit(2); };
for (const k of ["legend", "legendHex", "sprites", "work"]) if (!data[k] || typeof data[k] !== "object") fail(`the JSON has no "${k}"`);
const legend = data.legend;
for (const [name, s] of Object.entries(data.sprites)) {
  if (!Number.isInteger(s.w) || !Number.isInteger(s.h) || !Array.isArray(s.rows)) fail(`sprite ${name}: needs integer w, h and rows`);
  if (s.rows.length !== s.h || s.rows.some((r) => typeof r !== "string" || r.length !== s.w)) fail(`sprite ${name}: rows do not fit ${s.w}x${s.h}`);
  for (const r of s.rows) for (const ch of r) if (ch !== "." && legend[ch] === undefined) fail(`sprite ${name}: character ${JSON.stringify(ch)} is not in the legend`);
}
const checkPixels = (name, key, list) => {
  const s = data.sprites[name];
  for (const t of list) {
    if (!Array.isArray(t) || t.length !== 3 || !Number.isInteger(t[0]) || !Number.isInteger(t[1]) || typeof t[2] !== "string") fail(`work ${name}.${key}: a pixel is [x, y, char]`);
    if (t[0] < 0 || t[1] < 0 || t[0] >= s.w || t[1] >= s.h) fail(`work ${name}.${key}: pixel ${t[0]},${t[1]} is outside the ${s.w}x${s.h} sprite`);
    if (t[2] !== "." && legend[t[2]] === undefined) fail(`work ${name}.${key}: character ${JSON.stringify(t[2])} is not in the legend`);
  }
};
for (const [name, w] of Object.entries(data.work)) {
  if (!data.sprites[name]) fail(`work ${name}: no such sprite`);
  for (const [key, v] of Object.entries(w)) {
    if (key === "flash") checkPixels(name, key, v);
    else if (key === "work" || key === "idle") for (const ph of v) checkPixels(name, key, ph);
    else fail(`work ${name}: unknown key ${key}`);
  }
}

const q = (s) => JSON.stringify(s);
const px = (t) => `[${t[0]}, ${t[1]}, ${q(t[2])}]`;
const list = (l) => `[${l.map(px).join(", ")}]`;

const out = [];
out.push(`// GENERATED by tools/artb/gen.mjs from tools/artb/artb-slice.json (sha256 ${sha}). Do not edit: replace the JSON, run \`node tools/artb/gen.mjs\`.`);
out.push("// Art direction B, first slice (REQ-BFG-126, REQ-BFG-127): KILN, the ten FURNACE rigs and FURNACE's face. Pure data, no behaviour: src/render/artB.ts reads it.");
out.push("");
out.push("/** One pixel of a working-state overlay: x, y in the sprite's own pixels, a legend character ('.' clears that pixel). */");
out.push("export type ArtBPixel = readonly [number, number, string];");
out.push("export interface ArtBSpriteData { readonly w: number; readonly h: number; readonly rows: readonly string[] }");
out.push("/** `work`: two phases while the thing works; `idle`: phases of a slow idle flicker (the first is the plain sprite); `flash`: KILN's, one overlay. */");
out.push("export interface ArtBWorkData { readonly work?: readonly (readonly ArtBPixel[])[]; readonly idle?: readonly (readonly ArtBPixel[])[]; readonly flash?: readonly ArtBPixel[] }");
out.push("");
out.push(`export const ART_B_SHA256 = ${q(sha)};`);
out.push("");
out.push("/** One character -> a palette colour name of render/palette.ts C. */");
out.push("export const ART_B_LEGEND: Readonly<Record<string, string>> = {");
for (const [ch, name] of Object.entries(legend)) out.push(`  ${q(ch)}: ${q(name)},`);
out.push("};");
out.push("");
out.push("/** name -> { w, h, rows } (rows of legend characters, '.' = clear). */");
out.push("export const ART_B_SPRITES: Readonly<Record<string, ArtBSpriteData>> = {");
for (const [name, s] of Object.entries(data.sprites)) {
  out.push(`  ${q(name)}: {`);
  out.push(`    w: ${s.w}, h: ${s.h},`);
  out.push("    rows: [");
  for (const r of s.rows) out.push(`      ${q(r)},`);
  out.push("    ],");
  out.push("  },");
}
out.push("};");
out.push("");
out.push("/** sprite name -> the pixels that change while the thing works (idle flicker, working phases, KILN's flash). A sprite with no entry holds still. */");
out.push("export const ART_B_WORK: Readonly<Record<string, ArtBWorkData>> = {");
for (const [name, w] of Object.entries(data.work)) {
  out.push(`  ${q(name)}: {`);
  for (const [key, v] of Object.entries(w)) {
    if (key === "flash") out.push(`    flash: ${list(v)},`);
    else {
      out.push(`    ${key}: [`);
      for (const ph of v) out.push(`      ${list(ph)},`);
      out.push("    ],");
    }
  }
  out.push("  },");
}
out.push("};");
const text = out.join("\n") + "\n";

if (process.argv.includes("--check")) {
  let cur = "";
  try { cur = readFileSync(OUT_PATH, "utf8"); } catch { /* missing = differs */ }
  if (cur === text) { console.log(`gen.mjs --check: src/render/artBData.ts is what artb-slice.json (sha256 ${sha.slice(0, 16)}) generates`); process.exit(0); }
  const a = cur.split("\n"), b = text.split("\n");
  let i = 0;
  while (i < a.length && i < b.length && a[i] === b[i]) i++;
  console.error(`gen.mjs --check: src/render/artBData.ts differs from what artb-slice.json generates (first difference at line ${i + 1}); run \`node tools/artb/gen.mjs\``);
  process.exit(1);
}
writeFileSync(OUT_PATH, text);
console.log(`gen.mjs: wrote src/render/artBData.ts (${text.split("\n").length - 1} lines, ${Object.keys(data.sprites).length} sprites, ${Object.keys(data.work).length} work entries) from artb-slice.json sha256 ${sha.slice(0, 16)}`);
