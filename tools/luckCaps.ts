// Luck caps (0.6.2 TUNE-C, REQ-BFG-033; src/sim/harness/luck.ts): npm run luckcaps [-- --check | --dry] [--md file]
// The par player (typical policy) plays LUCK_SEEDS (48) real runs per hero, days 1-10; each dusk deck is read as
// LuckMeasures (value, 2-star parts, 3-star parts, parts of rare or better and of epic or better, bought turrets), and
// per hero-day ORDINARY luck is the field's nearest-rank P50 of each measure, GOOD luck its P90 (stars-aligned: no cap).
//   (default)  writes src/sim/harness/luckCapsData.ts (the committed table the tests read) and prints the table
//   --check    regenerates in memory and compares with the committed module: IDENTICAL, or DIFFERS (exit code 1, and the
//              hero-days that moved). Run it on a new head (a par-player, price or caravan change moves the caps).
//   --dry      prints the table, writes nothing
//   --md f     also writes the table as markdown to f (the report's caps table)
// No battles: about 30 s single-threaded.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { LUCK_HEROES, LUCK_Q, LUCK_SEEDS, MEASURES, luckCapsTable, type LuckCapsTable, type LuckMeasures } from "../src/sim/harness/luck";
import { maxGoldByDay } from "../src/sim/rivals";
import { flag } from "./workers";
import { scaleRules, setScaleRigs } from "../src/sim/scale"; // BUMP-1E P2e (REQ-BFG-098): the scaling world held on while the caps are read

export const DATA = "src/sim/harness/luckCapsData.ts";

const row = (m: LuckMeasures) => `{ ${MEASURES.map((k) => `${k}: ${m[k]}`).join(", ")} }`;

/** The data module's text (deterministic: the same table gives the same bytes). */
export function render(t: LuckCapsTable): string {
  const lines = [
    "// GENERATED by tools/luckCaps.ts (npm run luckcaps); do not edit. Check it with `npm run luckcaps -- --check`.",
    `// The luck caps (0.6.2 TUNE-C, REQ-BFG-033): per hero and day (index day - 1), ORDINARY = the par field's P50 and GOOD`,
    `// = its P90 (nearest rank) of each luck measure (src/sim/harness/luck.ts) over the par player's seeds 1-${t.seeds}.`,
    "// fingerprint: parRunFingerprint(hero), seed 1's run; tests/captains.luck.test.ts recomputes it to catch a stale table.",
    "",
    'import type { LuckCapsTable } from "./luck";',
    "",
    "export const LUCK_CAPS: LuckCapsTable = {",
    `  seeds: ${t.seeds},`,
    `  fingerprint: { ${LUCK_HEROES.map((h) => `${h}: "${t.fingerprint[h]}"`).join(", ")} },`,
    "  caps: {",
  ];
  for (const h of LUCK_HEROES) {
    lines.push(`    ${h}: [`);
    t.caps[h]!.forEach((c, i) => lines.push(`      { ordinary: ${row(c.ordinary)}, good: ${row(c.good)} }, // day ${i + 1}`));
    lines.push("    ],");
  }
  lines.push("  },", "};", "");
  return lines.join("\n");
}

const HEAD = ["value", "★2", "★3", "rare+", "epic+", "turrets"];

/** The table as markdown: per hero-day, the budget and each tier's caps. */
export function markdown(t: LuckCapsTable): string {
  const out = [
    `| hero | day | budget g | ${HEAD.map((h) => `ordinary ${h}`).join(" | ")} | ${HEAD.map((h) => `good ${h}`).join(" | ")} |`,
    `|---|---|---|${HEAD.map(() => "---").join("|")}|${HEAD.map(() => "---").join("|")}|`,
  ];
  for (const h of LUCK_HEROES) {
    t.caps[h]!.forEach((c, i) => out.push(`| ${h.toUpperCase()} | ${i + 1} | ${maxGoldByDay(i + 1)} | ${MEASURES.map((k) => c.ordinary[k]).join(" | ")} | ${MEASURES.map((k) => c.good[k]).join(" | ")} |`));
  }
  return out.join("\n");
}

function main(): void {
  const t0 = performance.now();
  const table = luckCapsTable(LUCK_SEEDS);
  const text = render(table);
  const secs = ((performance.now() - t0) / 1000).toFixed(1);
  console.log(`luck caps: ${LUCK_HEROES.length} heroes x ${LUCK_SEEDS} par runs (P${100 * LUCK_Q.ordinary} ordinary, P${100 * LUCK_Q.good} good) in ${secs} s; fingerprint ${LUCK_HEROES.map((h) => `${h} ${table.fingerprint[h]}`).join(", ")}`);
  console.log(markdown(table));
  const md = flag("md");
  if (md) writeFileSync(resolve(md), markdown(table) + "\n");
  if (process.argv.includes("--check")) {
    const old = readFileSync(resolve(DATA), "utf8");
    const same = old === text;
    console.log(`check: ${same ? "IDENTICAL" : "DIFFERS"}: regenerated ${text.length} bytes vs committed ${DATA} (${old.length} bytes)`);
    if (!same) {
      const a = old.split("\n"), b = text.split("\n");
      b.forEach((l, i) => { if (a[i] !== l) console.log(`  - ${a[i] ?? "(none)"}\n  + ${l}`); });
      process.exit(1);
    }
  } else if (!process.argv.includes("--dry")) {
    writeFileSync(resolve(DATA), text);
    console.log(`wrote ${DATA}`);
  }
}

// BUMP-1E P2e (SCALE-2d F6; SCALE-2e carry-over 9): the caps are read from the par player's runs with the scaling world on: setScaleRigs(true)
// held inside try/finally for the whole run (never withScaleRigs(async ...)). SCALE_RIGS is true in the code now, so this does nothing
// there; it makes the table independent of the constant.
const wasScale = scaleRules();
setScaleRigs(true);
try {
  main();
} finally {
  setScaleRigs(wasScale);
}
