// Stand-in pool CLI: npm run standins -- [--seed 1] [--pop 64] [--band 40,60] [--per 6]
//   [--workers N] [--out ../output] [--check]
// Writes src/sim/standInPoolData.ts (the bundled pool the game copies with src/sim/standInPool.ts)
// and <out>/standin-pool.md. --check regenerates in memory, compares with the committed data
// module and exits 1 if they differ (nothing is written). Battles fan out to worker threads;
// results are keyed by job, so the pool is identical for any --workers value.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { availableParallelism } from "node:os";
import { resolve } from "node:path";
import { isMainThread } from "node:worker_threads";
import { HEROES, RULES_VERSION, type HeroId } from "../src/sim/content";
import { validateBuild } from "../src/net/validate";
import { describeBuild } from "../src/sim/harness/report";
import { pct } from "../src/sim/harness/stats";
import { STANDIN_DEFAULTS, dataModuleText, genStandIns, standInCommand, type HeroDay, type StandInOpts } from "../src/sim/harness/standins";
import { spendOf } from "../src/sim/harness/tournament";
import { flag, num, serveJobs, workerRunner } from "./workers";

const DATA = "src/sim/standInPoolData.ts";

if (!isMainThread) serveJobs();
else {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}

async function main(): Promise<void> {
  const band = (flag("band") ?? STANDIN_DEFAULTS.band.join(",")).split(",").map(Number);
  if (band.length !== 2 || band.some((x) => !Number.isFinite(x) || x < 0 || x > 100) || band[0] >= band[1]) throw new Error("--band must be lo,hi percentiles, e.g. 40,60");
  const o: StandInOpts = {
    ...STANDIN_DEFAULTS,
    seed: num("seed", STANDIN_DEFAULTS.seed),
    pop: num("pop", STANDIN_DEFAULTS.pop),
    per: num("per", STANDIN_DEFAULTS.per),
    gauntlet: num("gauntlet", STANDIN_DEFAULTS.gauntlet),
    band: [band[0], band[1]],
  };
  if (o.per < 1 || o.pop < o.per) throw new Error("--pop must be at least --per, and --per at least 1");
  const check = process.argv.includes("--check");
  const nw = num("workers", Math.max(1, Math.min(availableParallelism() - 1, 23)));
  const pool = workerRunner(nw, import.meta.url);
  const t0 = performance.now();
  const res = await genStandIns(o, pool.run, (m) => console.log(m));
  await pool.close();
  const secs = (performance.now() - t0) / 1000;
  for (const hd of res.days) {
    for (const p of hd.picks) {
      const v = validateBuild(p.build, hd.day);
      if (!v.ok || p.build.hero !== hd.hero) throw new Error(`stand-in ${hd.hero} d${hd.day} #${p.idx} is invalid: ${v.errors.join("; ")}`);
    }
  }
  const text = dataModuleText(o, res.days);
  const path = resolve(DATA);
  if (check) {
    let old = "";
    try {
      old = readFileSync(path, "utf8");
    } catch {
      old = "";
    }
    const same = old === text;
    console.log(`check: ${same ? "IDENTICAL" : "DIFFERS"}: regenerated ${text.length} bytes in memory (${res.battles} battles, ${secs.toFixed(1)} s, ${nw} workers) vs committed ${DATA} (${old.length} bytes)`);
    process.exit(same ? 0 : 1);
  }
  writeFileSync(path, text);
  const out = resolve(flag("out") ?? "../output");
  mkdirSync(out, { recursive: true });
  writeFileSync(resolve(out, "standin-pool.md"), poolMarkdown(o, res.days, { battles: res.battles, secs, workers: nw, bytes: text.length }));
  console.log(`${res.battles} battles in ${secs.toFixed(1)} s on ${nw} worker(s); wrote ${DATA} (${text.length} bytes) and ${out}/standin-pool.md`);
}

const H = (h: HeroId) => HEROES[h].name;

function poolMarkdown(o: StandInOpts, days: HeroDay[], run: { battles: number; secs: number; workers: number; bytes: number }): string {
  const L = [
    "# BeltBattles stand-in pool (full purse)",
    "",
    `Generated by \`${standInCommand(o)}\` (rules ${RULES_VERSION}): ${run.battles} battles in ${run.secs.toFixed(1)} s on ${run.workers} worker thread(s).`,
    `Data module \`${DATA}\`: ${run.bytes} bytes (${(run.bytes / 1024).toFixed(1)} KB); loader \`src/sim/standInPool.ts\`.`,
    "",
    `- Population: ${o.pop} legal builds per hero and day (the harness generator plus a top-up), each costing at least ceil(0.9 x maxGoldByDay(day)).`,
    `- Score: win rate against a fixed gauntlet of that day's full-purse builds, ${o.gauntlet} per hero (${o.heroes.map(H).join(" and ")}), from another seed; ${o.seeds} seeds x both sides per pairing (${o.gauntlet * o.heroes.length * o.seeds * 2} battles per build).`,
    `- pct: strength percentile inside the population (share scoring lower, ties half). Picks: ${o.per} builds with pct in ${o.band[0]}-${o.band[1]}, nearest to evenly spaced targets; par = the pick nearest 50 (**bold**).`,
    `- Par vs ref: the par against heroRefBuild(hero, day) of each pool hero, ${o.refSeeds} seeds x both sides. Par vs elites: against that day's top ${o.elites} builds of each pool hero's population, ${o.seeds} seeds x both sides.`,
    "",
    "## Summary",
    "",
    `| hero | day | floor / budget | pop spend median [min-max] | extra draws | picks: cost | picks: pct | par pct | par vs ${o.heroes.map((h) => `${H(h)} ref`).join(" / ")} | par vs elites |`,
    `|---|---|---|---|---|---|---|---|---|---|`,
  ];
  for (const hd of days) {
    const sp = spendOf(hd.pop.map((c) => c.cost));
    const extra = hd.pop.reduce((s, c) => s + c.tries - 1, 0);
    const costs = hd.picks.map((p) => p.cost), pcts = hd.picks.map((p) => p.pct);
    L.push(`| ${H(hd.hero)} | ${hd.day} | ${hd.floor} / ${hd.budget} | ${sp.median} [${sp.min}-${sp.max}] | ${extra} | ${Math.min(...costs)}-${Math.max(...costs)} | ${Math.min(...pcts)}-${Math.max(...pcts)} | ${hd.picks[hd.par].pct} | ${o.heroes.map((h) => pct(hd.parVsRef[h] ?? 0)).join(" / ")} | ${pct(hd.parVsElites)} |`);
  }
  const short = days.filter((hd) => hd.short || hd.picks.some((p) => p.cost < hd.floor));
  const widened = days.filter((hd) => hd.widened);
  L.push("", "## Exceptions", "");
  L.push(short.length ? short.map((hd) => `- ${H(hd.hero)} day ${hd.day}: picks under the floor ${hd.floor}: ${hd.picks.filter((p) => p.cost < hd.floor).map((p) => p.cost).join(", ")} g`).join("\n") : `- Spend floor: none. Every pick of every hero and day costs at least ceil(0.9 x maxGoldByDay).`);
  L.push(widened.length ? widened.map((hd) => `- ${H(hd.hero)} day ${hd.day}: fewer than ${o.per} builds inside the band; the nearest outside it were used.`).join("\n") : `- Band: none. Every pick lies inside ${o.band[0]}-${o.band[1]}.`);
  for (const hd of days) {
    L.push("", `## ${H(hd.hero)} day ${hd.day} (floor ${hd.floor} of ${hd.budget} g)`, "", "| # | cost | pct | score | deck |", "|---|---|---|---|---|");
    hd.picks.forEach((p, i) => {
      const b = (s: string | number) => (i === hd.par ? `**${s}**` : `${s}`);
      L.push(`| ${b(i === hd.par ? `${i} par` : i)} | ${b(p.cost)} | ${b(p.pct)} | ${b(pct(p.score))} | ${describeBuild(p.build, hd.day)} |`);
    });
    L.push("", `Par: ${o.heroes.map((h) => `${pct(hd.parVsRef[h] ?? 0)} vs ${H(h)} ref`).join(", ")}; ${pct(hd.parVsElites)} vs the day's elites. Top elite: ${pct(hd.elites[0].score)} (${hd.elites[0].cost} g).`);
  }
  return L.join("\n") + "\n";
}
